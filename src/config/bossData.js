// Boss Ganimet ve Ödül Hesaplama
export function rollBossRewards(boss, playerClassId = 'warrior') {
  // Rastgele Altın
  const gold = Math.floor(Math.random() * (boss.maxGold - boss.minGold + 1)) + boss.minGold;
  
  // Rastgele EXP
  const exp = Math.floor(Math.random() * (boss.maxExp - boss.minExp + 1)) + boss.minExp;

  // Ekipman Düşme Şansı
  const droppedItems = [];
  const willDrop = Math.random() < boss.dropRate;

  if (willDrop && Array.isArray(ITEMS_DATABASE) && ITEMS_DATABASE.length > 0) {
    const dropCount = Math.floor(Math.random() * (boss.maxDrops - boss.minDrops + 1)) + boss.minDrops;

    // Oyuncunun sınıfına %70 şans, diğer sınıflara %30 şans
    const classItems = ITEMS_DATABASE.filter((it) => it.classId === playerClassId);

    for (let i = 0; i < dropCount; i++) {
      const pickClass = Math.random() < 0.70;
      const pool = (pickClass && classItems.length > 0) ? classItems : ITEMS_DATABASE;
      const randomItem = pool[Math.floor(Math.random() * pool.length)];

      droppedItems.push({
        ...randomItem,
        instanceId: `${randomItem.id}_boss_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
        droppedAt: new Date().toISOString(),
      });
    }
  }

  return {
    gold,
    exp,
    droppedItems,
  };
}
